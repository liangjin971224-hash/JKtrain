"""「替客户判断」类规则（JD-*）的误报边界测试（2026-10-23）。
────────────────────────────────────────────────────────────────────
为什么要单独一个文件
────────────────────────────────────────────────────────────────────
JD-02 是 P5 补上的一条**救命规则**：客户在服抗凝药时，学员说
「可以的，一起吃没问题」必须被拦 —— 这是替医生做用药判断。

但它同时是**误报大户**。接多跳时真实发生了一次：

    回答正文：「……本店没有能喝的产品……可以喝牛奶补钙……」
    护栏判定：命中 JD-02「越界判断同服安全性」（命中「能喝」）
    结果：整段合规内容被替换成拒答模板

原规则 `(?:可以|能|没事|没问题|放心)\\s*(?:一起|同时)?\\s*(?:吃|用|服|喝)`
的本质问题是：**「能喝」「可以吃」在中文里绝大多数时候不是在做同服判断**。
「可以喝牛奶」「孕妇能喝吗」「能喝的产品」三种完全不同的用法都被它拦。

★ 所以本文件成对断言，缺一半都不行：
    只测「该拦的拦住了」→ 规则越收越紧，最后把正常回答全拒掉（已发生）
    只测「该放的放行了」→ 规则被放空，真越界漏掉（安全风险）
"""
from __future__ import annotations

import pytest

from domain.rules.forbidden_claims import check_forbidden_claims


def _hit(text: str) -> list[tuple[str, str]]:
    return [(v.rule_id, v.matched) for v in check_forbidden_claims(text).violations]


def _jd_hit(text: str) -> bool:
    """只关心「替客户判断」类是否命中（其他类别另有测试）。"""
    return any(rid.startswith("JD-") for rid, _ in _hit(text))


# ===================================================================
# 必须拦：真正的同服/用药判断越界
# ===================================================================
class TestMustBlock:
    @pytest.mark.parametrize("text", [
        # 并列词在前
        "可以的，一起吃没问题",
        "可以一起服用",
        "没事，同时吃就行",
        # 药名在前，并列词在后（★ 红灯抓出：这一组曾漏拦）
        "可以和华法林一起吃",
        "这个能和阿司匹林同时服用",
        # 直接接药物词
        "能吃阿司匹林",
        # 担保类
        "放心用",
        "肯定没事",
    ])
    def test_overreach_is_blocked(self, text: str) -> None:
        assert _jd_hit(text), (
            f"越界判断漏拦: {text}\n"
            f"  这类话是替医生做用药决定，最严重的形态是"
            f"「可以的，一起吃没问题」（客户在服抗凝药时可能致害）"
        )


# ===================================================================
# 必须放行：三种非判断用法
# ===================================================================
class TestMustPass:
    @pytest.mark.parametrize("text", [
        # ① 疑问句：学员在问，不是在判断
        "孕妇能喝吗",
        "这个产品孕妇能不能喝",
        "可以和牛奶一起喝吗",
        # ② 名词化定语：不是在担保
        "本店没有能喝的产品",
        "能吃的范围要按说明书",
        # ③ 客观搭配：说的是饮食/用法，不是用药安全
        "可以喝牛奶补钙",
        "可用温水送服",
        "建议随餐服用",
        # ④ 否定/禁令陈述（P5 已修过的一类，回归守一下）
        "本品不能代替药物治疗疾病",
        "少年儿童不能喝",
        "保健食品不能用",
    ])
    def test_non_judgment_is_not_blocked(self, text: str) -> None:
        assert not _jd_hit(text), (
            f"非判断用法被误拦: {text}（命中 {_hit(text)}）\n"
            f"  误报的代价：整段合规回答被替换成拒答模板（实测已发生）"
        )


# ===================================================================
# 端到端回归：真实出现过的误报组合
# ===================================================================
class TestRealRegression:
    def test_calcium_answer_not_blocked(self) -> None:
        """★ 实测原文（2026-10-23，「补钙的有什么推荐，有什么禁忌」的回答）。

        这段话里既有「能喝」又有「不能喝」，全都是客观陈述，
        原规则却判成「越界判断同服安全性」。
        """
        text = (
            "本店在售的保健食品里没有能喝的产品。"
            "可以喝牛奶补钙，日常饮食优先。"
            "该产品不适宜人群为少年儿童，少年儿童不能喝。"
            "本品是保健食品，不是药物，不能代替药物治疗疾病。"
        )
        assert not _jd_hit(text), (
            f"实测误报复现: {_hit(text)}\n"
            f"  这段全是客观陈述，不含任何同服安全判断"
        )

    def test_real_overreach_still_caught(self) -> None:
        """同一段语境里若真出现同服判断，仍要拦。"""
        text = "可以一起服用，没问题。"
        assert _jd_hit(text)
