"""推理侧输出后处理：剥离 Markdown、截断回吐、统一收尾。

════════════════════════════════════════════════════════════════════
为什么把「格式干净」放在推理侧，而不是靠训练学
════════════════════════════════════════════════════════════════════
实测 v4 权重：答案正确，但输出尾部会回吐参考资料原文
（`| 序号 | 最容易说错的表述 |`、``` 代码块、`### 标题`）。

v5 试过靠训练解决——把 output 规范成「单段/200字/句号收尾」，
结果**格式干净了，但答案的正确表述丢了**（「有助于维持血压健康水平」
变成了「有助于改善血管弹性，降低血压」，后者是违规表述）。

结论：**模型该管内容，格式该管代码。**
让模型学「不输出 Markdown」是错配职责——同一批权重下，
用正则剥掉符号只需 3 行，且 100% 可靠；靠训练学则可能牺牲内容准确性。

因此本模块放在推理链路，对模型输出做最后一道清洗。
────────────────────────────────────────────────────────────────────
用法
────────────────────────────────────────────────────────────────────
    from infrastructure.llm.output_cleaner import clean_model_output
    answer = clean_model_output(raw_text)
"""
from __future__ import annotations

import re

#: Markdown 结构行：标题、表格、代码围栏、水平线、列表符号
_STRUCT_LINE = re.compile(
    r"^\s*(?:#{1,6}\s|```|\|.*\||[-:]{2,}\s*$|-{3,}\s*$|[*+]\s)", re.M
)

#: 行内加粗 / 斜体标记
_INLINE_MD = re.compile(r"\*{1,3}|_{2,}|`{1,3}")

#: 参考资料回吐的起点标记。
#: 模型答完后常接一句「【参考资料】」然后抄原文，从这行起全部丢弃。
#:
#: ★ 实测补充（2026-11-06，Ollama 3B 在真实链路上）：
#:   模型还会以**孤立标题**或**表单式文档**的形式回吐，例如
#:     「…补充说明。参考资料：」                        ← 裸标题无【】
#:     「客户记录 ═══════ 到店时间：… 客户编号：…」       ← 抄案例表单
#:     「── 主诉 ── …」                                ← 小节分隔线
#:   这些不在原规则里，导致答案后面拖一整段无关内容。
#:
#: ★ 不用 `\n` 前缀：单行文本里「…。参考资料：」出现在句号之后，
#:   前面是空格不是换行（实测漏匹配）。改为「句末标点或空白之后」。
_ECHO_START = re.compile(
    r"(?:^|(?<=[。！？；）\)\s]))"
    r"(?:【参考资料】|【结构化事实】|\[1\]\s*《|⚠️|以下为错误示范|"
    r"以下是错误示范|错误示范[：:]|参考资料[：:]|参考来源[：:]|"
    # ★ 括号包裹的引用（实测新变体）：
    #   「…不能代替药物治疗疾病。 （参考资料：[1] 《D006 产品知识手册》一、基础信息）」
    #   模型把出处塞进括号跟在答案后面，要连同括号一起砍。
    r"[（(]\s*参考资料|"
    # 表单式文档的表头：客户记录 / 客户档案 / 接待记录 + 分隔线
    r"(?:客户记录|客户档案|接待记录|到店记录)\s*[═=\-─]{3,}|"
    # 裸露的表单标题词（后面紧跟正文，实测会残留「客户记录 建议您…」）
    r"(?:客户记录|客户档案|接待记录|到店记录)(?=\s|$)|"
    # 独立的小节分隔线（整行只有符号）
    r"[═=\-─━]{4,}|"
    # 「── 主诉 ──」这类小节标记
    r"[─━]{2,}\s*\S{1,8}\s*[─━]{2,})"
)

#: 表单字段：出现这些说明在抄表单，而非回答问题。
#:
#: ★ 不能用 `^\s*` 锚定行首：模型输出的表单经常是**单行**的
#:   （换行在生成时被压平），锚定后一个都匹配不到（实测 0 命中）。
#:   改为「字段名 + 冒号」的宽松匹配，靠后续 `_looks_like_answer()` 防误伤。
_FORM_FIELD = re.compile(
    r"(?:到店时间|客户编号|客户来源|同行人|接待人|联系方式|现住址|"
    r"主诉|用药情况|过敏史|生活方式|既往史|家族史|"
    r"体格检查|测量结果|服务过程|跟进计划)\s*[：:]"
)

#: 句子结束符
_SENT_END = "。！？」"

#: 「回答腔」标志：出现这些说明模型在回答问题，而不是抄文档。
#: 只用于「是否该整段丢弃」的判定，不用于内容过滤。
_ANSWER_TONE = re.compile(
    r"(?:不对|不可以|不能|不建议|应该|应说|正确(?:的)?(?:表述|说法)|"
    r"建议|请注意|需要注意的是|按照资料|按资料|根据资料|"
    r"保健食品不是药物|不属于|不能用|不得|可以说|这样(?:说)?(?:对吗|不对)?)"
)


def _looks_like_answer(text: str) -> bool:
    """判断文本是否是在「回答问题」而非「抄文档」。

    实测依据：抄表单的输出里几乎没有判断性、劝阻性词汇，
    全是「字段：值」。而真正回答一定会出现「不对/应该/建议/不能」这类词。
    """
    return bool(_ANSWER_TONE.search(text))


def _extract_answer_sentences(text: str, *, limit: int = 2) -> str:
    """从一段（可能混着表单的）文本里，挑出「像回答」的句子。

    ★ 用途：模型有时把回答写在表单**后面**（实测出现过），
      直接按回吐起点砍掉会把回答一起丢。这里按句切分后只留像回答的。
    """
    # ★ 先摘掉残留在开头的表单标题词。
    #   实测：砍掉「客户记录 ═══」后，tail 从「客户记录 建议您…」开始，
    #   按句切分时这句被整句保留，结果答案前面挂着「客户记录 」
    text = re.sub(
        r"^\s*(?:客户记录|客户档案|接待记录|到店记录)\s*[：:═=\-─]*\s*", "", text)

    # 按中文句末标点切句，保留标点
    parts = re.split(r"(?<=[。！？])", text)
    picked: list[str] = []
    for p in parts:
        p = p.strip()
        if not p:
            continue
        # 跳过纯表单/分隔线片段
        if _FORM_FIELD.search(p) or re.fullmatch(r"[═=\-─━\s]+", p):
            continue
        if _looks_like_answer(p):
            picked.append(p)
    return "".join(picked[:limit])


def clean_model_output(text: str, *, max_len: int = 400) -> str:
    """清洗模型输出。

    Args:
        text: 模型原始输出。
        max_len: 最大长度。超出时截到最后一个完整句子。

    Returns:
        清洗后的文本：无 Markdown、无回吐、单段、句号收尾。
    """
    if not text:
        return ""

    t = text

    # 0) ★ 判断「这段是不是在抄表单」。
    #    实测：问「阿司匹林能吃鱼油吗」，Ollama 3B 返回一整个
    #    「客户记录 ═══ 到店时间：… 客户编号：… 主诉：…」表单。
    #
    #    但有两种情况要分开：
    #      a) 整段都是表单 → 丢弃
    #      b) 表单后面接了真正回答（"不对，应该说…"）→ 要保留回答
    #    判据：表单字段 ≥2 且**没有**回答腔 → 是 (a)
    form_heavy = len(_FORM_FIELD.findall(t)) >= 2

    # 1) 砍掉「回吐参考资料」的尾巴。如果整段都是表单，砍完就是空。
    m = _ECHO_START.search(t)
    if m:
        tail = t[m.start():]
        # ★ 回吐段里如果含有「回答腔」，说明模型把回答写在了表单后面，
        #   这种要保住回答部分，不能整段丢弃（实测误伤过一次）。
        if _looks_like_answer(tail):
            # 从回吐段里取出第一句像回答的，作为结果
            t = t[: m.start()] + " " + _extract_answer_sentences(tail)
        else:
            t = t[: m.start()]

    # 整段是表单且没有回答腔 → 判为无效
    if form_heavy and not _looks_like_answer(t):
        return ""

    # 2) 去掉结构行（整行 Markdown）
    t = _STRUCT_LINE.sub("", t)

    # 3) 去掉行内标记
    t = _INLINE_MD.sub("", t)

    # 4) 压缩空白，合并成一段
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r"\n{2,}", "\n", t).strip()
    # 段内换行转成句号分隔，避免出现无标点的拼接
    t = re.sub(r"\n+", " ", t)
    t = re.sub(r"\s{2,}", " ", t).strip()

    # 5) 清掉残留的空标点组合
    t = re.sub(r"^[\s：:；;，,。、]+", "", t)
    t = re.sub(r"[，,；;、]\s*。", "。", t)
    t = re.sub(r"。{2,}", "。", t)

    # 6) 限长：截到最后一个完整句子，避免半句
    if len(t) > max_len:
        cut = max(t.rfind(c, 0, max_len) for c in _SENT_END)
        t = t[: cut + 1] if cut > max_len // 2 else t[:max_len]

    # 7) 句号收尾
    if t and t[-1] not in _SENT_END:
        t = t.rstrip("，,；;、 ")

    return t.strip()


def has_markdown(text: str) -> bool:
    """检查文本是否含 Markdown 结构（用于自检与测试）。"""
    return bool(_STRUCT_LINE.search(text)) or bool(_INLINE_MD.search(text))
