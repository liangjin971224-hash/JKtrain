"""禁用表述检测（六类）。

★ 这是全项目合规性最核心的一份规则文件。
  任何输出路径都必须经过它（经 `OutputGuardrail` 调用）。

────────────────────────────────────────────────────────────────────
规则来源（逐条可追溯，评审问"凭什么"时要能答）
────────────────────────────────────────────────────────────────────
| 类别 | 来源 |
|---|---|
| 第一类 疾病治疗 | `06_正式内容/D005` 第四章 4.1 |
| 第二类 药物替代 | `06_正式内容/D005` 第四章 4.2 |
| 第三类 绝对化 | `06_正式内容/D005` 第四章 4.3 |
| 第四类 效果承诺 | `06_正式内容/D005` 第四章 4.4 |
| 第五类 他人经验背书 | `06_正式内容/D005` 第四章 4.5 |
| 第六类 缺「有助于」 | `06_正式内容/D005` 第三章 3.1 对照表 |
| 普通食品功能声称 | `06_正式内容/D008` 第一章 1.2 |

────────────────────────────────────────────────────────────────────
设计要点
────────────────────────────────────────────────────────────────────
1. **全部规则都是 critical**。
   本项目的立场：禁用词没有"轻微违规"这一说，说了就是违法宣传风险。
   分级（high/medium）留到 P5 评阅场景用于区分「必须改」和「建议改」。

2. **必须避免误报**。
   护栏过度拦截会把正常业务堵死。所以：
     · 「有助于维持血糖健康水平」合规 → 不能因含"血糖"就拦
     · 「本品不能代替药物治疗疾病」合规 → 不能因含"治疗"就拦
   处理方式：先做「合规白名单」放行，再做「禁用模式」检测，见 `_is_compliant`。

3. 规则是纯函数、纯常量，**零依赖**，可秒级全测。
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from domain.value_objects import Severity


@dataclass(frozen=True, slots=True)
class ClaimViolation:
    """一条违规命中。"""

    rule_id: str
    category: str          # 六类之一
    matched: str           # 命中的原文片段
    pattern: str           # 命中的规则
    severity: Severity = Severity.CRITICAL
    reason: str = ""       # 为什么违规（给业务看的解释）


@dataclass(frozen=True, slots=True)
class ClaimCheckResult:
    """检测结果。

    ★ 不含 score / verdict 字段（约束 #3：系统只出卡不出分）。
      `has_critical` 是布尔判断，不是分数。
    """

    violations: tuple[ClaimViolation, ...] = ()

    @property
    def has_critical(self) -> bool:
        """是否有 critical 级违规（这类必须拦截）。"""
        return any(v.severity.must_block for v in self.violations)

    @property
    def max_severity(self) -> Severity | None:
        """最严重的级别。无命中返回 None。

        注意 `max(..., key=...)` 返回的是**元素本身**，不是 key 值。
        所以要再取一次 `.severity`。
        """
        if not self.violations:
            return None
        worst = max(self.violations, key=lambda v: v.severity.order)
        return worst.severity

    @property
    def is_clean(self) -> bool:
        return not self.violations

    def categories(self) -> tuple[str, ...]:
        """命中的类别（去重）。"""
        return tuple(dict.fromkeys(v.category for v in self.violations))


# ===================================================================
# 合规白名单：先放行，避免误报
# ===================================================================
# ★ 为什么必须先放行：
#   法定警示语「保健食品不是药物，不能代替药物治疗疾病」里含"治疗"，
#   若直接跑禁用模式会被判违规 —— 而这句话恰恰是**必须说**的。
#   同理「有助于维持血糖健康水平」含"血糖"。
#
# 做法：把合规表述整段挖掉，再在剩余文本上跑检测。
#: ★ 分两组（实测踩坑后拆分）：
#:   原来是一个大元组，导致「有助于增强免疫力」这类**保健食品批准功能原文**
#:   在普通食品判定时也被放行 → 漏放违规声称。
#:
#:   批准功能是**保健食品专属**的。普通食品没有批准功能，
#:   说「有助于增强免疫力」就是违反《食品安全法》。
_COMPLIANT_PHRASES = (
    # ---- A 组：任何类别都合规（法定警示语、边界话术）----
    # 法定警示语（D004 4.1，不可改写）
    "保健食品不是药物，不能代替药物治疗疾病",
    "保健食品不是药物",
    "本品不能代替药物",
    "不能代替药物治疗疾病",
    "不是药物，不能代替药物治疗疾病",
    # 合规的边界说明（D001/D002 的标准话术）
    "个体差异较大，不能承诺具体效果",
    "不能承诺具体效果",
    "没有固定的见效时间",
    "保健食品是长期调理",
    "不建议长期服用",
    "请咨询医生",
    "建议遵医嘱",
    "需遵医嘱",
    # 停药风险的客观描述（D005 4.2 原文「可能导致客户延误治疗」）。
    # ★ 这是**风险说明**，不是产品效果宣称：
    #   违规话术只会说「吃了就不用吃药」，不会说「本品会延误治疗」。
    #   实测误拦：ev2-05 回答「药物替代类最危险的是『可以停药』…
    #   可能导致客户延误治疗」被整段拦掉。
    "延误治疗",
    "延误病情",
    "耽误治疗",
    "延误最佳治疗",
    # 「服用治疗药物的人群」是 D002/D006 的原话，指药物类别，不是本品的治疗宣称。
    # 实测误报：hq-01「客户正在服阿司匹林，属于治疗药物」被 DC-01 拦掉。
    "治疗药物",
    # 对**产品**的否定治疗表述（A2，2026-11-08）。
    # ★ 只放行否定式，不放行「可以治疗 / 治疗糖尿病 / 根治」等肯定式；
    #   也不放行「不建议治疗」这类对疾病的建议（可能有害）。
    # 实测误报：v3/FT 回答常写「本品不是治疗药物，不能治疗疾病」，
    # DC-01 命中「治疗」→ 重试/流式误拒。
    "不是治疗药物",
    "不能代替药物治疗",
    "不能代替治疗",
    "不能用于治疗",
    "不用于治疗",
    "不能作为治疗",
    "非治疗",
)

#: 需要**正则**判定的合规否定式（不能简单按字面挖）。
#:
#: ★ 为什么不能把「不能治疗」「不是治疗」直接放进 `_COMPLIANT_PHRASES`：
#:   会把「客户问**能不能治疗**，我说可以的」里的「不能治疗」也挖掉，
#:   导致真正的肯定宣称漏检（2026-11-08 pytest 抓到）。
#:   用负向后视 `(?<!能)` 只放行真正的否定，不放行「能不能治疗」。
_COMPLIANT_PATTERNS = (
    re.compile(r"(?<!能)不能治疗"),
    re.compile(r"(?<!能)不是治疗"),
)

#: 培训语境的「提及」句式（无引号，但语义是禁止/否定/名词化提及）。
#:
#: ★ 为什么需要（A2b，2026-11-08 实测）：
#:   v3/FT 回答会写：
#:     「绝不能暗示可以停药」        → DR-03 命中「可以停药」
#:     「别人没事不代表您也一定没事」→ JD-03 命中「一定没事」
#:     「若涉及停药/替代药物」        → DR-01 命中「替代药物」
#:   这些是**教学/劝阻**，不是产品宣称。无引号，现有 `_QUOTED_*` 覆盖不到。
#:   只挖「否定/禁止/名词化提及」的整段，不挖裸的肯定句：
#:     「这个可以停药」仍然拦。
_MENTION_PATTERNS = (
    re.compile(
        # ★ `不能(?!不说)`：排除「不能不说…」这种双否/转折；
        # ★ 字符类排除逗号：不能跨小句匹配（「不能在柜台说，但确实能降血糖」）。
        r"(?:不能(?!不说)|不可|不得|不要|严禁|禁止|绝不|避免|切勿)"
        r"[^。；，\n]{0,12}(?:暗示|说|写|提|使用|承诺|出现)"
        r"[^。；，\n]{0,16}"
        r"(?:可以停药|一定没事|替代药物|降血糖|降血脂|根治|最有效|唯一|绝对安全|治疗)"),
    re.compile(
        r"(?:不代表|不等于|并不意味着|不等于说)[^。；，\n]{0,20}"
        r"(?:一定没事|有效|安全|可以停药|替代药物)"),
    re.compile(r"(?:涉及|关于|针对)[^。；，\n]{0,8}(?:停药|替代药物)"),
    # 「禁止使用他人背书：不要说很多人吃了都好」这类教学条目。
    re.compile(
        r"(?:禁止|不要|不能说|严禁|避免)[^。；，\n]{0,8}(?:使用|说|写)?"
        r"[^。；，\n]{0,10}(?:他人背书|经验背书)"
        r"[^。；，\n]{0,20}(?:很多人吃了都好|很多人说好|别人都说|我朋友也说)"),
)


def _strip_mentions(text: str) -> str:
    """挖掉「教学/劝阻/名词化提及」的整段（无引号场景）。

    只匹配带否定/禁止/提及引导词的片段；裸肯定句不受影响。
    """
    out = text
    for pat in _MENTION_PATTERNS:
        out = pat.sub(lambda m: "□" * (m.end() - m.start()), out)
    return out
#:
#: 为什么单独一组：这是国家批准的保健功能目录原文，
#: 对保健食品是**必须原样使用**的合规表述；
#: 对普通食品则是**禁止**的（普通食品没有任何批准功能）。
_HEALTH_FOOD_ONLY_PHRASES = (
    "有助于维持血糖健康水平",
    "有助于维持血脂（胆固醇/甘油三酯）健康水平",
    "有助于维持血脂健康水平",
    "有助于维持血压健康水平",
    "有助于增强免疫力",
    "有助于改善睡眠",
    "有助于改善骨密度",
    "有助于控制体内脂肪",
)


def _strip_negated_claims(text: str) -> str:
    """挖掉「纯否定陈述」片段，但**排除双重否定与转折**。

    ★ 关键（实测三次才定下来）：
      否定陈述要放行，但下面这类**形式否定、语义肯定**的必须继续判违规：
          不可否认它能降血糖
          不能不说这个能降血脂
          不可以治疗，但能缓解

      做法：对每个 `_NEGATED_CLAIM` 匹配，先看是否与双否/转折重叠。
        重叠   → **不挖**（留给违规规则抓）
        不重叠 → 挖掉（否定陈述放行）

    为什么不用「先挖双否、再挖否定」：
      双否片段被挖掉后，里面的功效词也一起没了，
      违规规则就抓不到 —— 反而变成漏放。

    Args:
        text: 已处理过合规表述与引述的文本。

    Returns:
        挖掉「纯否定陈述」后的文本（等长占位符）。
    """
    dangerous = [m.span() for m in _DOUBLE_NEGATION.finditer(text)]

    def _overlaps(start: int, end: int) -> bool:
        return any(not (end <= ds or start >= de) for ds, de in dangerous)

    out = text
    # 从后往前替换，避免位置偏移
    for m in reversed(list(_NEGATED_CLAIM.finditer(text))):
        if _overlaps(*m.span()):
            continue                     # 双否/转折：不挖，留给违规规则
        s, e = m.span()
        out = out[:s] + "□" * (e - s) + out[e:]
    return out


def _strip_noun_phrases(text: str) -> str:
    """挖掉「疾病预防、治疗功能」这类**名词化并列短语**。

    ★ 为什么需要（用户实测截图暴露的真实 bug）：
      流式按句切分可能在顿号处断开：
          前段：「…或疾病预防、」
          后段：「治疗功能，也不能替代药物。」
      后段单独检测就命中「治疗」→ 误拦。
      结果是**同一句话非流式通过、流式拒答**。

      而「治疗功能」在这里是**被禁止的对象**（"不能宣称治疗功能"），
      不是功效宣称。

    ★ 挖除范围限定得很窄：
      只处理「预防、治疗 + 功能/作用/功效」这种名词化搭配。
      不含「能治」「可治疗」「治疗效果很好」这类动词用法 —— 那些仍拦。

    Args:
        text: 待处理的文本。

    Returns:
        挖掉名词化并列短语后的文本。
    """
    def _blank(m: re.Match[str]) -> str:
        return "□" * (m.end() - m.start())

    return _NOUN_PHRASE.sub(_blank, text)


def _strip_compliant(text: str, *, health_food_only: bool = True) -> str:
    """把合规表述从文本中挖掉，返回剩余部分。

    不是替换成空格，而是替换成等长占位符，保留字符位置便于定位命中位置。

    Args:
        text: 原始文本。
        health_food_only: 是否把「保健食品批准功能原文」也算合规。
            ★ 文本方向检测（`check_forbidden_claims`）不区分产品类别，
              所以保守地按 True 处理（放行批准功能原文）。
              普通食品类别判定必须传 False。
    """
    out = text
    phrases = list(_COMPLIANT_PHRASES)
    if health_food_only:
        phrases += list(_HEALTH_FOOD_ONLY_PHRASES)

    # 按长度降序，避免短串先替长串（「保健食品不是药物」截断整句）
    for phrase in sorted(phrases, key=len, reverse=True):
        if phrase in out:
            out = out.replace(phrase, "□" * len(phrase))
    # 正则型合规否定式（负向后视，排除「能不能治疗」）
    for pat in _COMPLIANT_PATTERNS:
        out = pat.sub(lambda m: "□" * len(m.group(0)), out)
    return out


# ===================================================================
# 引述语境识别（★ 真实误拦的主要来源）
# ===================================================================
# 问题背景：
#     培训文档与合规话术里大量出现「反例教学」，例如：
#         ❌ 不能说「降血脂」
#         不能说"治疗"这类词
#         禁止使用「唯一」这种绝对化表述
#     这些句子**在教什么不能说**，本身是合规内容。
#     但纯正则会把引号里的禁用词当成违规命中。
#
# ★ 放行的边界必须极窄，否则真违规会漏过：
#     ✅ 放行：否定词 + 引号包住禁用词        「不能说『降血脂』」
#     ❌ 不放行：否定词后没有引号             「不能说降血脂，但这个确实有用」
#     ❌ 不放行：肯定语境                     「这个能降血脂」
#
#     也就是说：**只有"被引号括起来的禁用词"才可能是引述**。
#     违规话术通常不会给自己的禁用词加引号。
#
# 为什么不用「长否定词表」：
#     否定词越多，误放风险越大。
#     实测「不可声称能治疗糖尿病」这种没有引号的句子，
#     语义上有「声称」作为动作词，确实是引述——
#     这类单独用少量固定短语处理，不扩散成通用否定词表。

#: 引述语境：否定引导词 + 一个或多个引号片段。
#:
#: ★ 必须支持**连续多个引号**（实测教训）：
#:      「❌ 不能说“降血脂”“调节血脂”“治疗高血脂”等」
#:   只匹配第一对引号的话，后两个引号片段会被当成独立违规命中。
#:
#: ★ 引号之间**只允许顿号/空格**，不允许逗号（实测教训）：
#:      最初写成 `[、，,\s]*`，把逗号也吃进匹配范围，
#:      结果「❌ 不能说“降血脂”，我们这款确实降血脂」
#:      整个前半段连逗号一起被挖掉，后半句的真违规被移位漏检。
#:      中文化学里多个并列引述用顿号（“A”“B”），
#:      逗号通常意味着**句子转折**（“，但…”），必须留给后续检测。
#:
#: ★ **不加**「等…」这类可选收尾语（同样的坑）：
#:      `等[^。！？\n]{0,10}` 会把后续文字吞进匹配范围。
#:      现在只挖「否定词 + 引号片段」本身，引号外文字一律照常检测。
_QUOTED_NEGATION = re.compile(
    r"(?:不能说|不可说|不能说成|不可称|不能称|不要用|不可用|不能用|"
    r"禁止使用|禁止说|严禁使用|严禁说|避免使用|不应使用|不该说|"
    r"错误说法|错误表述|反例|误用|应改为|正确说法|应为|改写为)"
    r"[^。！？\n]{0,12}?"
    # 一个或多个引号片段；片段之间只允许顿号或空白，不吃逗号句号
    r"(?:[「『\"'“”‘’][^」』\"'“”‘’\n]{1,24}[」』\"'“”‘’][、\s]*)+",
)

#: ★ 已废弃：无引号反例行的「局部挖掘」。#:
#: 最初想支持「❌ 不能说：治疗」这种不带引号的写法，
#: 但实测发现无法与真违规可靠区分：
#:     「❌ 不能说：治疗，我们这个确实能治好」
#: 挖掉「治疗」后，后半句「确实能治好」若不含禁用词就整体放行——
#: 而这句话本身就是典型的违规话术。
#:
#: 判断：**无引号的引述不应放行**。
#: 理由：违规话术通常不会给禁用词加引号，而合规的反例教学一定会用引号
#: 或「不能说」等明确引导词 + 引号。宁可误拦（人工复核一条），
#: 不可漏放（违法宣传）。
#:
#: 因此只保留下面这个「仅当内容段完整结束、无后续文字」的严格版本：
#: 「❌ 不能说：治疗」单独成句可以放行，「❌ 不能说：治疗，…」不放行。
_BARE_NEGATION_WHOLE_LINE = re.compile(
    r"^\s*(?:[-*+]\s*)?(?:[❌✗×]|错误说法|错误表述|反例)\s*[:：]?\s*"
    r"(?:不能说|不可说|不可|不要用|禁止|严禁)?\s*[:：]?\s*"
    r"[^\n，,。；;！!？?]{1,30}\s*$",
)


# ===================================================================
# 劝阻性否定表述（★ 端到端真实输出暴露的误拦）
# ===================================================================
# 问题背景：
#     D005 要求的标准话术里，有大量「否定 + 禁用词根」的**正确表述**：
#         不可擅自停药或替代治疗
#         请遵医嘱，不可自行停药或改变治疗方案
#         不能代替药物治疗疾病
#     这些句子含「治疗」「停药」等被禁词根，但语义是**劝阻**，
#     恰恰是合规要求必须说的话。
#
# ★ 放行条件（必须同时满足，不能放宽）：
#     ① 出现劝阻否定词（不可/不能/不得/禁止/严禁/切勿/请勿/不应）
#     ② 否定词管辖范围内的是「停药 / 替代 / 治疗方案 / 自行用药」这类
#        行为词，而不是「产品能治病」这类效果宣称
#
# ★ 不放行的反例（必须保持拦截）：
#     「可以停降压药了」      —— 无否定词
#     「吃了就能替代药物」    —— 无否定词
#     「不用吃药」            —— 由 DR-02 规则负责
#
# 这段是**整句挖掉**，因为「不可擅自停药或替代治疗」是一个完整语义单元，
# 拆开检测必然误判。
_DISSUASION = re.compile(
    r"(?:不可|不能|不得|不应|不该|禁止|严禁|切勿|请勿|不要)"
    r"[^。！？\n]{0,10}?"
    r"(?:擅自|自行|随意)?\s*"
    r"(?:停药|减药|加药|换药|改药|断药|替代治疗|替代药物|"
    r"改变治疗方案|调整用药|调整治疗方案|自行用药|停止治疗)"
    r"[^。！？\n]{0,12}",
)


# ===================================================================
# 双重否定 / 转折（★ 必须在否定陈述放行之前排除）
# ===================================================================
# 问题背景（实测）：
#     「不可否认它能降血糖」「不能不说这个能降血脂」「不可以治疗，但能缓解」
#   这些句子**形式是否定，语义是肯定**，必须判违规。
#   若直接走 `_NEGATED_CLAIM` 放行，就会漏放。
#
# 处理：见 `_strip_negated_claims` —— 匹配到这类模式时，**不挖掉**否定陈述，
#   让违规规则继续抓到里面的功效词。
_DOUBLE_NEGATION = re.compile(
    r"(?:不可否认|不能不说|不得不说|不可忽视|不能不提|"
    r"不是不|并非不|无不|未尝不)"
    r"[^。！？\n]{0,12}"
    # 转折词：前半否定、后半肯定
    r"|(?:不能|不得|不可|不应|不该)[^。！？\n，,；;]{0,12}"
    r"(?:，|,|；|;|但|但是|不过|然而|可是)"
    r"[^。！？\n]{0,12}",
)


# ===================================================================
# 否定性排除陈述
# ===================================================================
# 问题背景：
#     合规回答常用「排除法」说明边界，例如：
#         它不用于治疗高血脂症
#         不具有「降血脂」的治疗作用
#         不能声称治疗疾病
#         不在本品批准范围内
#     这些句子含「治疗」「降血脂」等被禁词根，但语义是**否定**，
#     恰恰是最严谨、最合规的表述。
#
# ★ 与「劝阻性表述」的区别：
#     劝阻性 = 劝人不要做某事（不可擅自停药）
#     否定性 = 陈述本品不具备某功能（不用于治疗）
#   两者都必须放行，但匹配模式不同，所以分两条规则。
#
# ★ 只放行「否定词 + 禁用词根」紧邻的形式，不放宽到整句：
#   反例（必须仍拦）：「不能不说这个能降血脂」
#                      —— 「不能」和「降血脂」之间有「不说这个能」，
#                         不满足「紧邻」条件
_NEGATED_CLAIM = re.compile(
    # ★ 用「否定前缀 + 必有动词」的组合，而不是枚举搭配
    #
    #   实测教训：原先枚举了 `不涉及`，但真实文本是「不能涉及」，
    #   逐条枚举永远会漏。改成组合式。
    #
    # ★ 但「不」不能单独用（实测踩坑）：
    #   `不可以治疗，但能缓解` 被 `不` + 中间 + `治疗` 误判为否定陈述，
    #   而它其实是**转折**——前半句否定、后半句肯定。
    #   所以要求否定词必须**紧跟动词**（`不` 只在少数固定搭配里单独用）。
    r"(?:(?:不能|不得|不可|不应|不该|并非|绝非|无|非)"
    r"(?:用于|具备|具有|含|涉及|属于|提供|声称|宣称|明示|暗示|作|有|"
    r"包括|包含|承诺|等同|视为|作为|当成|当作|超过|达到)?"
    # `不` 只允许这些固定搭配，不允许裸「不 + 任意词」
    r"|不(?:用于|具备|具有|含|涉及|属于|提供|声称|宣称|明示|暗示|"
    r"作|有|包括|包含|承诺|等同|视为|作为|当成|当作)"
    r")"
    # 中间插入语允许顿号（、）但不允许逗号（，）与分号
    #
    #   为什么：顿号表示**并列**，「疾病预防、治疗功能」是一个整体概念；
    #   逗号/分号表示**转折或分句**，「不能这个，但可以那个」是真违规。
    #   实测踩坑：「普通食品不能宣称任何保健功能或疾病预防、治疗功能」
    #   因顿号被排除而误拦 —— 这句是《广告法》原文表述，完全合规。
    r"[^。！？\n，,；;]{0,20}?"
    r"(?:治疗|治愈|根治|疗效|降血糖|降血脂|降血压|抗炎|消炎|"
    r"防癌|抗癌|增强免疫力|提高免疫力|改善睡眠|减肥|"
    r"保健功能|医疗作用|疾病治疗|疾病预防)"
    r"[^。！？\n]{0,10}",
)

#: 「指代医生/医院已有诊疗」的合规表述。
#:
#: ★ 用户实测暴露的误拦（第二轮）：
#:     请以医生的诊断和治疗方案为准
#:     遵医嘱，按医生的治疗方案执行
#:     配合医生的治疗
#:   这些含「治疗」，但主语是**医生/医院**，在陈述「客户已有的诊疗」——
#:   恰恰是 D005 要求必须说的话（提示就医）。
#:
#: ★ 与违规宣称的区分靠**主语**：
#:     主语 = 医生/医院/治疗方案 → 合规（指代第三方诊疗）
#:     主语 = 本品/这个/它      → 违规（宣称自己的治疗作用）
#:
#: ★ 只认「医生/医院/医嘱/诊疗」这类明确的第三方主体，
#:   不放宽到「治疗」两个字本身 —— 那样会漏放「这个能治疗」。
_MEDICAL_CONTEXT = re.compile(
    r"(?:医生|医师|医院|药店|药师|临床|专业|正规医疗机构|医疗机构)"
    r"[^。！？\n]{0,12}?"
    r"(?:诊断|治疗|用药|处方|方案|建议|意见)"
    r"|(?:诊断|治疗)\s*方案"
    r"|(?:遵|听|按|依)\s*(?:医嘱|医生(?:的)?(?:话|建议|方案|安排)?)"
    r"|(?:接受|配合|进行|正在)\s*(?:医生|医院|正规)?\s*(?:的)?\s*治疗"
    r"|(?:诊断|治疗|用药|处方)\s*(?:和|与|及)\s*(?:治疗|用药|处方|方案|诊断)",
)


#: 「指称语境」：在**说这个词本身不能用**，而不是在使用它。
#:
#: ★ 实测误拦（2026-10-23，教学场景高发）：
#:     「乌发属于功能暗示，不符合普通食品的法规要求，因此不能这样表述。」
#:   —— 这是在**解释法规**，是培训系统最该说的话，
#:      却因为含「乌发」被拦。同类还有：
#:     「「乌发」是功能暗示，普通食品不能说。」
#:     「不能宣称乌发功效。」
#:
#: ★ 判定依据（两个必要条件之一）：
#:    ① 被引号/书名号括起来： 「乌发」『乌发』"乌发"
#:    ② 后面紧跟「属于/是 + 暗示/违规/禁用/不能说」这类**评价性谓语**
#:       或前面有「不能/不得/禁止 + 宣称/使用/说」
#:
#: ★ 关键反例（必须仍拦）：
#:     「黑芝麻有乌发养颜的功效」—— 在使用，不是指称
#:     「乌发养颜的功效」        —— 在使用
_QUOTED_TERM = re.compile(
    # ★ 引号种类必须齐全（实测教训 2026-10-31）：
    #   模型会用直引号写 '防癌'，旧字符类只认「」『』""，
    #   漏掉单引号后「没有'防癌'这一项」仍被当成违规命中。
    r"[「『\"“'‘]([^」』\"”'’]{1,12})[」』\"”'’]"
    # 形态二：「X 属于/是 功能暗示/违规表述」
    r"|([^\s，。！？、；：「」『』\"“”]{1,12}?)\s*"
    r"(?:属于|是|系)\s*(?:功能暗示|功能声称|违规|禁用|违法|不允许|不可用|"
    r"绝对化用语|医疗用语|敏感词|不能说的)"
    # 形态三：「不能/不得/禁止 宣称/使用/说 X」
    r"|(?:不能|不得|不可|禁止|严禁|避免|不要)\s*"
    r"(?:宣称|声称|使用|说|写|标注|出现|提)\s*"
    r"([^\s，。！？、；]{1,12})",
)


def _strip_named_terms(text: str) -> str:
    """挖掉「指称某个词不能用」的片段。

    ★ 为什么必须单独处理：
      培训系统里大量句子是「不能说『降血脂』」这种**反例教学**，
      它本身完全合规，甚至是最关键的合规知识点。
      纯正则会把引号里的禁用词当命中 → 把正确内容拦掉。

    ★ 与 `_QUOTED_NEGATION` 的区别：
      `_QUOTED_NEGATION` 处理「❌ 不能说"降血脂"」这种带显式否定前缀的；
      本函数处理「「乌发」属于功能暗示」这种以**评价谓语**表达的。
    """
    def _blank(m: re.Match[str]) -> str:
        return "□" * (m.end() - m.start())

    return _QUOTED_TERM.sub(_blank, text)



#: 「疾病预防、治疗功能」这类**名词化并列短语**。
#:
#: ★ 为什么必须单独处理（用户实测截图暴露）：
#:   流式按句切分时可能在顿号处断开，产生：
#:       前段：「普通食品不能宣称任何保健功能或疾病预防、」
#:       后段：「治疗功能，也不能替代药物。」
#:   后段单独检测就命中「治疗」，而它在上下文里是接续前段的**同一概念**。
#:
#:   这会导致同一句话「非流式通过、流式被拦」——
#:   用户看到的正是这个现象（同一问题两次，一次正常一次拒答）。
#:
#: 处理：识别「治疗功能」这类**明显不构成功效宣称**的搭配。
#:   注意限定很窄——只是「治疗 + 功能/作用」这种名词化搭配，
#:   不含「能治」「可治疗」这类动词用法。
_NOUN_PHRASE = re.compile(
    # 形态一：完整的并列短语「疾病预防、治疗功能」
    #   这是《广告法》的标准表述，无论前后文都合规
    r"(?:疾病)?(?:预防|防止)\s*、?\s*(?:治疗|治愈)\s*(?:功能|作用|功效|宣称|宣传)?"
    # 形态二：只有后半段「治疗功能」——流式切分后可能单独出现
    #
    #   ★ 必须**同时**满足两个条件才算合规：
    #     ① 前面不是「有/具有/能/可/该」（那些是功效宣称）
    #     ② 后面紧跟名词化标记（的+宣称/宣传/表述/标注，或直接接宣称类词）
    #
    #   实测踩了三轮：
    #     v1 只判「治疗+功能」→ 「该产品有治疗作用」被误放
    #     v2 加前置排除 → 「这个治疗功能很明显」仍被误放
    #     v3（当前）再加「必须带名词化标记」→ 正确
    #
    #   为什么 v3 有效：「治疗功能很明显」是**评价**（在说这个功能强），
    #   而「治疗功能的宣称」是**指称对象**（在被禁止的那个说法本身）。
    r"|(?<![有具能可该])(?:治疗|治愈)\s*、?\s*(?:功能|作用|功效)"
    r"(?:\s*的\s*(?:宣称|宣传|表述|标注|描述)"
    r"|\s*(?:宣称|宣传|表述|标注|描述))",
)


def _strip_quoted_negations(text: str) -> str:
    """把「引述禁用词」的片段挖掉，避免误判为违规。

    ★ 放行边界（保守）：
      ① 否定引导词 + **引号** + 禁用词   → 放行（引述）
      ② 「❌ 不能说：xxx」**整行就到此为止** → 放行（独立反例行）
      ③ 「❌ 不能说：xxx，…」后面还有话   → **不放行**（无法判断后半句）

    只有「被引号括起来的禁用词」才可靠地是引述。
    无引号的形式一律按可疑处理，宁可误拦。

    Returns:
        挖掉引述片段后的文本（等长占位符，保留字符位置）。
    """
    def _blank(m: re.Match[str]) -> str:
        return "□" * (m.end() - m.start())

    out = _QUOTED_NEGATION.sub(_blank, text)
    # 劝阻性否定表述（「不可擅自停药或替代治疗」这类合规话术）
    out = _DISSUASION.sub(_blank, out)
    # 否定性排除陈述（「不用于治疗高血脂症」这类边界说明）
    # ★ 内部会排除双否/转折，避免漏放「不可否认它能降血糖」
    out = _strip_negated_claims(out)
    # 名词化的并列短语（「疾病预防、治疗功能」）——流式切分后也要能放行
    out = _strip_noun_phrases(out)
    # 指代医生/医院已有诊疗的表述（「以医生的诊断和治疗方案为准」）
    # ★ 主语是医生时，「治疗」不是本品的宣称，是提示就医
    out = _MEDICAL_CONTEXT.sub(_blank, out)

    # 只处理「整行就是一个反例」的情况，不碰后面还有内容的行
    lines = out.split("\n")
    for i, line in enumerate(lines):
        if _BARE_NEGATION_WHOLE_LINE.match(line):
            lines[i] = "□" * len(line)
    return "\n".join(lines)


