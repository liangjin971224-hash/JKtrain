def neutralize_compliant(text: str, *, allow_youzhuyu: bool = True) -> str:
    """把文本中的**合规表述**全部挖成占位符，返回剩余部分。

    ★ 这是「判定合规性」的**唯一前置处理**，必须被所有类别共用。

    ────────────────────────────────────────────────────────────
    为什么必须是公开函数（实测踩坑）
    ────────────────────────────────────────────────────────────
    原来这套挖除链只写在 `check_forbidden_claims` 内部，
    而 `product_category.check_claim_allowed`（普通食品功能声称判定）
    用的是**另一套裸正则**，没有共用。

    后果（用户实测发现）：
        「普通食品不能宣称任何保健功能或疾病预防、治疗作用。」
      —— 这是《广告法》原文式的**禁止性陈述**，完全合规，
         但在普通食品类别下被判「命中治疗」→ 误拦。

    同一套标准被复制成两份实现，就必然出现这种漂移。
    项目里已有同类教训（评阅与护栏共用 `_strip_compliant`），
    现在把它提取成公开入口，两个判定器共用。

    Args:
        text: 原始文本。
        allow_youzhuyu: 是否放行「有助于 X」形式。
            ★ **必须按类别传**（实测踩坑）：
              · 保健食品 → True。批准功能原文就是「有助于维持血脂……」，
                不放行会把合规回答全拦掉。
              · 普通食品 → False。普通食品**没有**批准功能，
                「有助于增强免疫力」对它是实打实的违规声称。
              实测曾因统一传 True，导致「有助于增强免疫力」
              在普通食品下被漏放。

    Returns:
        挖掉合规片段后的文本（等长占位符，位置不变）。
    """
    if not text:
        return text

    out = _strip_compliant(text, health_food_only=allow_youzhuyu)
    out = _strip_quoted_negations(out)
    # 「有助于 X」形式整体放行（仅保健食品的批准功能原文适用）
    if allow_youzhuyu:
        out = re.sub(
            r"有助于[\u4e00-\u9fff（）()/·a-zA-Z]{2,20}", "□" * 4, out)
    # 劝阻性 / 否定性排除 / 名词化并列 / 指代医生诊疗
    out = _DISSUASION.sub(lambda m: "□" * (m.end() - m.start()), out)
    out = _strip_negated_claims(out)
    out = _strip_noun_phrases(out)
    out = _MEDICAL_CONTEXT.sub(lambda m: "□" * (m.end() - m.start()), out)
    # 指称语境（「「乌发」属于功能暗示」「不能宣称乌发功效」）
    out = _strip_named_terms(out)
    # 教学/劝阻/名词化提及（无引号的「不能暗示可以停药」等）
    out = _strip_mentions(out)
    return out


def check_forbidden_claims(text: str) -> ClaimCheckResult:
    """检测文本中的违规功能声称。

    Args:
        text: 待检测文本（用户问题或模型输出）。

    Returns:
        命中的违规项。无命中返回空结果。
        `has_critical=True` 的项必须拦截，不得输出。

    Note:
        本函数不做改写建议（改写由上层负责）。
        检测前会先挖掉合规表述白名单，避免误报法定警示语。
    """
    if not text or not text.strip():
        return ClaimCheckResult()

    # ★ 统一走 `neutralize_compliant`（与普通食品判定共用同一套放行逻辑）
    #   历史原因：这段曾内联在这里，导致 product_category 用另一份实现，
    #   出现「同一句话在一处放行、另一处拦截」的漂移。
    working = neutralize_compliant(text)

    violations: list[ClaimViolation] = []
    for rule in _RULES:
        for m in rule.pattern.finditer(working):
            # 用占位符坐标回原文取片段，便于业务看到「到底哪句错了」
            start, end = m.span()
            original = text[start:end] if end <= len(text) else m.group(0)
            violations.append(ClaimViolation(
                rule_id=rule.rule_id,
                category=rule.category,
                matched=(original or m.group(0)).strip(),
                pattern=rule.pattern.pattern,
                severity=Severity.CRITICAL,
                reason=rule.reason,
            ))

    # 去重：同一 rule_id + 同一片段只记一次
    seen: set[tuple[str, str]] = set()
    unique: list[ClaimViolation] = []
    for v in violations:
        key = (v.rule_id, v.matched)
        if key in seen:
            continue
        seen.add(key)
        unique.append(v)

    return ClaimCheckResult(violations=tuple(unique))
