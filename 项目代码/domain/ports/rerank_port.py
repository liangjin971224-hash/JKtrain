"""重排端口。

作用：对融合后的候选集**按「问题-文档」的相关性重新打分**。

────────────────────────────────────────────────────────────────────
为什么需要它（这不是可选优化）
────────────────────────────────────────────────────────────────────
RRF 是「位置融合」：`score = Σ 1/(k + rank)`。
一条文档在向量路排第 1、在图谱路排第 1，得分完全一样——
**它只看排名，不看内容**，判断不出「这段到底有没有回答问题」。

真实例子（本项目）::

    问：在吃阿司匹林能吃鱼油吗

    向量 Top1：讲鱼油成分那段（语义相似度高，但没提禁忌）
    BM25 Top1：提到「阿司匹林」那段（只是顺带提了一句）
    图谱命中： P001 的不适宜人群（真正的答案）

    三者在 RRF 后排名接近，谁进 Top5 靠运气。

Rerank 是**交叉编码**（cross-encoder）：把「问题 + 文档」拼在一起过模型打分，
能识别出「这段在讲成分、不在讲禁忌」。两者互补：

    RRF    快、无需模型、三路平等   盲区：不看内容
    Rerank 准、看内容              代价：慢、要模型、只能处理少量候选

────────────────────────────────────────────────────────────────────
两条不能破的约束（写在这里，防止实现时忘）
────────────────────────────────────────────────────────────────────
1. **权限过滤必须在 Rerank 之前**。不能先排后滤——否则受限内容已经参与了
   排序，即使最终被过滤掉，排名信息也可能受影响。
   本端口只接收**已过滤**的候选，不再做权限判断。
2. **Rerank 只看相关性，不看合规性**。它可能把一段违规话术排到第一
   （因为语义最像），所以输出护栏照旧执行，两者不能互相替代。
"""
from __future__ import annotations

from abc import ABC, abstractmethod

from domain.value_objects import FusedHit


class RerankPort(ABC):
    """候选重排端口（cross-encoder）。"""

    @abstractmethod
    def rerank(
        self,
        query: str,
        candidates: list[FusedHit],
        *,
        top_k: int = 5,
    ) -> list[FusedHit]:
        """按相关性重排并截断。

        Args:
            query: 用户问题原文（不接受改写后的检索文本——
                重排要判断的是「这段是否回答了**用户问的**问题」）。
            candidates: 已融合、**已过滤权限**的候选集。
                建议传 20 条左右：太少则重排无意义，太多则延迟涨。
            top_k: 返回条数。

        Returns:
            重排后的前 top_k 条，**保持 FusedHit 类型**（便于调用方
            继续复用 chunk / sources 字段）。

        Notes:
            实现必须遵守：
            - `candidates` 为空时返回空列表，不抛异常；
            - `top_k <= 0` 时返回空列表；
            - 不改变入参对象（FusedHit 是 frozen，天然满足）。
        """
        raise NotImplementedError
