#: 「最接近项 ≠ 等同项」这条约束的说明，供上层拼 hint 时引用。
#:
#: 例：客户说「改善精力」，目录最接近的是「缓解体力疲劳」（第 7 项）。
#:     但**不能**对客户说「本品批准功能是改善精力」——
#:     批准功能只能用目录原文，改一个字都是违规声称。
NEAREST_NOT_EQUAL = (
    "注意：这只是「目录中最接近的一项」，**不等于**该需求就是批准功能。"
    "对外只能说目录原文的表述，不得把客户的说法当作批准功能。"
)

#: 从问题里抽「需求片段」。
#:
#: 「改善体脂都可以吃什么保健品」→「改善体脂」
#: 「补钙的有什么推荐」          →「补钙」
_DEMAND = re.compile(
    r"([\u4e00-\u9fff]{2,8}?)(?=都可以|有哪些|有什么|能吃|可以吃|适合|推荐|$)"
)


def demand_terms(question: str) -> list[str]:
    """从问题里抽出「客户想要什么」的片段。

    Args:
        question: 子查询问句。

    Returns:
        候选片段（去重保序）。可能为空 —— 空表示这句话里没有明确需求，
        调用方应退回普通检索，**不要猜**。
    """
    text = (question or "").strip()
    if not text:
        return []

    out: list[str] = []
    for m in _DEMAND.finditer(text):
        frag = m.group(1).strip()
        # 去掉结尾的「的」（「补钙的」→「补钙」）
        frag = frag.rstrip("的")
        if len(frag) >= 2 and frag not in out:
            out.append(frag)
    return out


def absent_reason(question: str) -> str:
    """这句话是否在问一个**目录里确定没有**的功能。

    Args:
        question: 子查询问句。

    Returns:
        非空字符串 = 目录里确定没有，值是可以直接讲给学员的原因。
        空串 = 不确定 / 有对应项（调用方应按正常流程走）。

    ★ 与 `guess_efficacy_ids` 的关系：
      两者可能同时命中（「关节酸痛想补骨密度」既有关节又有关）。
      上层要**两个都处理**：能答的答，不能答的说明原因。
      不要因为一个命中就忽略另一个。
    """
    lowered = (question or "").lower()
    for word, reason in _ABSENT_DEMANDS.items():
        if word in lowered:
            return reason
    return ""


def guess_efficacy_ids(question: str,
                       catalog: list[tuple[str, str]] | None = None,
                       *,
                       include_absent: bool = False) -> list[str]:
    """猜这句话可能对应目录里的哪几项。

    Args:
        question: 子查询问句。
        catalog: 目录快照 `[(efficacy_id, name)]`。为空时只用同义词表 ——
            **能猜到就猜，猜不到就返回空**，不硬凑。

    Returns:
        候选 efficacy_id 列表（去重保序）。**空列表是合法结果**：
        意味着「这句话不是在问某个功能」（如「客户进店第一步」）。

    Note:
        返回的顺序有意义：同义词表命中的在前（更可靠），
        对撞命中的在后。
    """
    terms = demand_terms(question)
    if not terms:
        return []

    ids: list[str] = []

    # ---- 1. 同义词表（最可靠）----
    lowered = (question or "").lower()
    for word, eid in _SYNONYMS.items():
        if word in lowered and eid not in ids:
            ids.append(eid)

    # ---- 2. 与目录名称做核心词对撞 ----
    if catalog:
        for term in terms:
            for eid, name in catalog:
                if eid in ids:
                    continue
                if _matches(term, name):
                    ids.append(eid)

    return ids


def _matches(term: str, catalog_name: str) -> bool:
    """口语片段与目录名称是否指同一件事。

    判据（任一成立）：
        ① 连续双字命中：口语里有两字连续出现在目录名里
        ② 全部单字命中，且口语长度 ≥ 2：字都出现过（顺序不限）
        ③ 目录名去虚词后是口语的子串（或反之）

    ★ ② 最宽，容易误报（「血压」对「血脂」共享「血」）——
      但它只在**没有**更强的①③时才用，且结果只是「候选」，
      真正的结论由图谱返回的产品决定。宁可多查一项，不要漏掉一个高频问法。
    """
    if not term or not catalog_name:
        return False

    core = _FILLER.sub("", _PREFIX.sub("", catalog_name))
    if term in core or core in term:
        return True

    # ① 连续双字命中
    for i in range(len(term) - 1):
        bigram = term[i:i + 2]
        if bigram in core:
            return True

    # ③ 去掉前缀再比一次（「体脂」vs「控制体内脂肪」的 core 已去过虚词）
    clean = _PREFIX.sub("", catalog_name)
    if term in clean:
        return True

    # ② 全部单字命中（排除弱区分力的字）
    chars = {c for c in term if c not in _WEAK_CHARS}
    if len(chars) >= 2 and chars.issubset(set(clean)):
        return True

    return False


