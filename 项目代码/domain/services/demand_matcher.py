"""口语需求词 → 批准功能目录项 的匹配（纯领域，零 IO）。

────────────────────────────────────────────────────────────────────
它解决的是一个**合规准确性**问题
────────────────────────────────────────────────────────────────────
问「改善体脂都可以吃什么保健品」时，只查产品会得到「0 个产品」。
此时模型面对两种完全不同的情形，说法必须不同：

    A. 目录里没有这个功能
       →「保健食品不允许声称『改善体脂』这个功能」

    B. 目录里有，但本店在售产品没有声称它的
       →「法规允许声称『有助于控制体内脂肪』（目录第 9 项），
          但本店在售的保健食品没有这项批准功能」

★ 实测踩到的真实错误（2026-10-23，接多跳时）：
    真实库里 `EFF_09「有助于控制体内脂肪」` **存在**，但 0 个产品声称它。
    只查产品拿到 0，模型就编成「目录中没有『改善体脂』等表述」——
    **把法规说错了**。合规培训系统教错法规，比不回答严重得多。

────────────────────────────────────────────────────────────────────
为什么不用「包含匹配」了事
────────────────────────────────────────────────────────────────────
目录原文是「有助于控制体内脂肪」，客户说的是「体脂」。
两个词**互不为子串**（「体脂」隔着一个「内」字），
`"体脂" in "有助于控制体内脂肪"` 是 False。
硬列一张「体脂→EFF_09」的表能解决这一条，但来一个新说法就得改代码。

所以改成**核心词对撞**：
    目录项的核心词 = 去掉「有助于/辅助/改善/维持/控制/补充」等虚词后的实词组合
    客户说的词   = 再拆成 2-gram
    命中数 ≥ 阈值 → 认为是同一个功能

    例：「体脂」的 2-gram = {体脂}
        「控制体内脂肪」的 2-gram = {控制,制体,体内,内脂,脂肪}
        直接对撞命中 0。所以额外允许「单字对撞」：
        「体脂」的 2 个字都在「控制体内脂肪」里出现 → 判为相关。

    ★ 单字对撞会带来误报（「血压」和「血脂」共享「血」字），
      所以阈值设为「**连续**双字命中 或 全部单字命中且长度≥2」，
      并且**只用于找候选**，最终结论仍由调用方看图谱返回的产品决定。

────────────────────────────────────────────────────────────────────
这层是「找候选」，不是「做判定」
────────────────────────────────────────────────────────────────────
本模块只回答「客户说的这个词可能是目录里的哪几项」，
**不判断该不该推荐、也不生成任何话术**。
判定与话术在应用层与护栏里，这里越界会把合规逻辑拆散。
"""
from __future__ import annotations

