#: 目录名称里的虚词/前缀。去掉后才好和口语对撞。
_PREFIX = re.compile(
    r"^(?:有助于|辅助|可以|能够)+"
)
_FILLER = re.compile(r"(?:有助于|辅助|改善|维持|控制|补充|调节|缓解|增强|促进|增加)")

#: 这些字单独拿出来没有区分力，参与「单字对撞」会把不相关的东西连起来。
#: 例：「有」「的」「水」「用」。
