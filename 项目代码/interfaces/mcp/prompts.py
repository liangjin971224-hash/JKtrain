"""MCP 提示模板：`expression_polish`。

════════════════════════════════════════════════════════════════════
为什么提示也要做成 MCP 能力
════════════════════════════════════════════════════════════════════
项目里有一条「组织表达」红线：改文字时**不能改数字、不能加事实、
不能加强语气**。这条规则原本写在培训文档里，靠人记住。

做成 Prompt 的好处：规则**固化在模板字符串里**，不依赖使用者记性。
外部 AI 助手拿到这个模板，就必须按约束改写——这比写条文档管用。

────────────────────────────────────────────────────────────────────
三条约束的来历（都不是凭空写的）
────────────────────────────────────────────────────────────────────
1. **不改数字**：月度报告里有「命中率 4/6」「练习 3 次」，
   改写成「大部分命中」「练了几次」就无法审计。
2. **不加事实**：曾出现把「客户自述血脂偏高」润色成「客户血脂偏高」，
   丢掉「自述」二字，性质从「客户说的」变成「我们认定的」。
3. **不加强语气**：「建议咨询医生」被改成「建议立即就医」，
   责任边界变了。
"""
from __future__ import annotations

import logging

from interfaces.mcp.identity import McpIdentity
from interfaces.mcp.policy import require_prompt

logger = logging.getLogger(__name__)

#: 允许的场景（白名单）。
#: ★ 不同场景的约束强度不同：月度报告最严（对外），日常总结稍宽。
SCENES = {
    "monthly_report": "月度培训报告（对外，最严格）",
    "daily_summary": "日报（内部）",
    "drill_comment": "演练评语（对学员）",
}

#: 场景附加约束。
_SCENE_RULES = {
    "monthly_report": (
        "这是对外的月度报告：不得出现评价性形容词（如「优秀」「不足」），"
        "只陈述可核对的事实与计数。"
    ),
    "daily_summary": (
        "这是内部日报：可以精简，但不得删除数字与时间。"
    ),
    "drill_comment": (
        "这是给学员的评语：只描述观察到的行为，不做能力判定，不给分数。"
    ),
}


def expression_polish_template(text: str, scene: str = "daily_summary") -> str:
    """生成润色提示词。

    Args:
        text: 待改写文本。
        scene: 场景（monthly_report / daily_summary / drill_comment）。

    Returns:
        完整的提示词字符串。
    """
    scene_key = scene if scene in SCENES else "daily_summary"
    scene_label = SCENES[scene_key]
    extra = _SCENE_RULES[scene_key]

    return f"""请润色下面这段文字，用于【{scene_label}】。

必须遵守（违反任何一条，这次改写就是失败的）：
1. **不改任何数字**：日期、次数、比例、剂量、金额一律原样保留。
2. **不添加任何事实**：原文没说的，不要补充、不要推测、不要「合理推断」。
3. **不加强语气**：原文写「建议咨询医生」，不要改成「必须就医」；
   原文写「自述」，不要删掉变成「确认」。
4. **不删除限定词**：「可能」「自述」「初步」「仅供参考」要保留。

{extra}

输出要求：
- 只输出改写后的正文，不要解释你改了什么。
- 不要加标题、不要加列表符号。
- 长度与原文相当，不要扩写。

待改写原文：
---
{text}
---
"""
